import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(
  root,
  "src",
  "features",
  "share-telegram-story",
  "worker",
  "story-video.worker.ts",
);
const workerOutputPath = join(root, "public", "workers", "story-video.worker.mjs");
const mediabunnySourcePath = join(
  root,
  "node_modules",
  "mediabunny",
  "dist",
  "bundles",
  "mediabunny.min.mjs",
);
const mediabunnyOutputPath = join(root, "public", "vendor", "mediabunny.min.mjs");

const [buildResult, mediabunny] = await Promise.all([
  build({
    bundle: true,
    conditions: ["worker", "browser"],
    entryPoints: [sourcePath],
    external: ["mediabunny"],
    format: "esm",
    legalComments: "none",
    minify: false,
    minifyWhitespace: true,
    platform: "browser",
    target: "es2022",
    write: false,
  }),
  readFile(mediabunnySourcePath),
]);
const bundledWorker = buildResult.outputFiles[0]?.text;
if (!bundledWorker) {
  throw new Error("The story worker bundle is empty.");
}
const mediabunnyImportPattern = /\bfrom\s*["']mediabunny["'];?/g;
const worker = bundledWorker.replace(
  mediabunnyImportPattern,
  'from"/vendor/mediabunny.min.mjs";',
);
if (/\bfrom\s*["']mediabunny["']/.test(worker)) {
  throw new Error("The mediabunny worker import could not be rewritten.");
}
if (!worker.includes('from"/vendor/mediabunny.min.mjs"')) {
  throw new Error("The mediabunny worker import is missing from the bundle.");
}

await Promise.all([
  mkdir(dirname(workerOutputPath), { recursive: true }),
  mkdir(dirname(mediabunnyOutputPath), { recursive: true }),
]);
await Promise.all([
  writeFile(
    workerOutputPath,
    `// Generated by scripts/build-story-worker.mjs. Do not edit directly.\n${worker}`,
  ),
  writeFile(mediabunnyOutputPath, mediabunny),
]);

console.log("Telegram story worker assets generated.");
